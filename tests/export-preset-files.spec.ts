import { test, expect } from '@playwright/test'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { DEFAULT_EXPORT_OPTIONS, exportPresetSettings, type SavedExportPreset } from '../src/shared/export-options'
import { launchDesktop, stopDesktop, openFixture, setOpenDialog, setSaveDialog, clickNativeMenu } from './desktop-helpers'

const preset = (name: string, header: string): SavedExportPreset => ({ name, format: 'pdf', settings: exportPresetSettings({ ...DEFAULT_EXPORT_OPTIONS, header }) })

test('预设 JSON 导入先预览冲突，可保留或覆盖并重命名，导出不携带程序授权', async () => {
  const session = await launchDesktop()
  try {
    const source = await openFixture(session, 'preset-document.md', '# Untouched source\n')
    const initial = await session.page.evaluate(presets => window.desktop.patchPreferences({ export: { savedPresets: presets, pandocPath: '/private/example/pandoc', customPresets: [{ name: 'Private converter', executable: '/private/example/command', args: ['{input}', '{output}'], template: '/private/example/template', extension: 'txt', input: 'markdown' }], customPreset: 'Private converter' } }), [preset('A', 'existing')])
    expect(initial.ok).toBe(true)
    const incoming = path.join(session.root, 'incoming-presets.json')
    const writeIncoming = async (presets: SavedExportPreset[]) => writeFile(incoming, JSON.stringify({ kind: 'qtypora-export-presets', version: 1, presets }))
    const readPresets = () => session.page.evaluate(async () => { const result = await window.desktop.bootstrap(); return result.ok ? result.data.preferences.export.savedPresets : [] })
    await writeIncoming([preset('A', 'imported'), preset('B', 'new')])
    await clickNativeMenu(session, '更多导出格式与设置…')
    await setOpenDialog(session, [incoming])
    await session.page.getByRole('button', { name: '导入预设 JSON…', exact: true }).click()
    const preview = session.page.getByRole('group', { name: '预设导入预览', exact: true })
    await expect(preview).toContainText('A · PDF · A4（同名冲突）')
    await expect(preview.getByRole('radio', { name: '保留已有同名预设，仅添加新名称（默认）' })).toBeChecked()
    expect(await readPresets()).toEqual([preset('A', 'existing')])
    await preview.getByRole('button', { name: '取消导入', exact: true }).click()
    expect(await readPresets()).toEqual([preset('A', 'existing')])
    await session.page.getByRole('button', { name: '导入预设 JSON…', exact: true }).click()
    await preview.getByRole('button', { name: '导入（保留已有同名预设）', exact: true }).click()
    await expect.poll(readPresets).toEqual([preset('A', 'existing'), preset('B', 'new')])
    await session.page.getByLabel('选择导出预设', { exact: true }).selectOption('A')
    await session.page.getByLabel('内建导出预设名称').fill('Renamed')
    await session.page.getByRole('button', { name: '重命名所选预设', exact: true }).click()
    await expect.poll(readPresets).toEqual([preset('B', 'new'), preset('Renamed', 'existing')])
    await writeIncoming([preset('Renamed', 'replacement'), preset('C', 'third')])
    await session.page.getByRole('button', { name: '导入预设 JSON…', exact: true }).click()
    await preview.getByRole('radio', { name: '使用导入内容覆盖同名预设' }).check()
    await preview.getByRole('button', { name: '导入并覆盖同名预设', exact: true }).click()
    await expect.poll(readPresets).toEqual([preset('B', 'new'), preset('Renamed', 'replacement'), preset('C', 'third')])
    const output = path.join(session.root, 'portable-presets.json')
    await setSaveDialog(session, output)
    await session.page.getByRole('button', { name: '导出预设 JSON…', exact: true }).click()
    await expect(session.page.getByRole('region', { name: '预设文件' }).getByRole('status')).toContainText('预设已导出')
    const text = await readFile(output, 'utf8')
    const portable = JSON.parse(text)
    expect(Object.keys(portable).sort()).toEqual(['kind', 'presets', 'version'])
    expect(portable).toMatchObject({ kind: 'qtypora-export-presets', version: 1 })
    expect(portable.presets).toEqual(await readPresets())
    expect(text).not.toMatch(/private\/example|executable|pandocPath|customPresets|template/)
    expect(await readFile(source, 'utf8')).toBe('# Untouched source\n')
    await session.app.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }) })
    await session.page.getByRole('button', { name: '导入预设 JSON…', exact: true }).click()
    await expect(preview).toHaveCount(0)
    await setOpenDialog(session, [incoming])
    await writeFile(incoming, JSON.stringify({ kind: 'qtypora-export-presets', version: 0, presets: [] }))
    await session.page.getByRole('button', { name: '导入预设 JSON…', exact: true }).click()
    await expect(session.page.getByRole('alert')).toContainText('仅支持版本 1')
    expect((await readPresets()).length).toBe(3)
    expect(session.errors).toEqual([])
  } finally { await stopDesktop(session) }
})

test('导入预览后另一窗口新增同名，提交保留策略仍保护最新配置', async () => {
  const session = await launchDesktop()
  try {
    await openFixture(session, 'preset-concurrent.md', '# Presets\n')
    const incoming = path.join(session.root, 'late-presets.json')
    await writeFile(incoming, JSON.stringify({ kind: 'qtypora-export-presets', version: 1, presets: [preset('Late', 'imported'), preset('New', 'new entry')] }))
    await setOpenDialog(session, [incoming])
    await clickNativeMenu(session, '更多导出格式与设置…')
    await session.page.getByRole('button', { name: '导入预设 JSON…', exact: true }).click()
    const preview = session.page.getByRole('group', { name: '预设导入预览', exact: true })
    await expect(preview).toContainText('Late · PDF · A4（新增）')
    const nextWindow = session.app.waitForEvent('window')
    await session.page.evaluate(() => window.desktop.newWindow())
    const second = await nextWindow
    await second.locator('.cm-content').waitFor()
    const otherResult = await second.evaluate(presets => window.desktop.applyExportPresetImport(presets, 'replace'), [preset('Late', 'other window')])
    expect(otherResult.ok).toBe(true)
    if (process.env.QTYPORA_TEST_VISIBLE === '1') {
      const nativeWindow = await session.app.browserWindow(session.page)
      await nativeWindow.evaluate(window => { window.show(); window.focus() })
      await expect.poll(() => nativeWindow.evaluate(window => window.isFocused())).toBe(true)
      await session.page.bringToFront()
    }
    await expect(preview).toContainText('Late · PDF · A4（同名冲突）')
    await preview.getByRole('button', { name: '导入（保留已有同名预设）', exact: true }).click()
    await expect(preview).toHaveCount(0)
    const state = await session.page.evaluate(() => window.desktop.bootstrap())
    expect(state.ok && state.data.preferences.export.savedPresets).toEqual([preset('Late', 'other window'), preset('New', 'new entry')])
    const replacement = await session.page.evaluate(presets => window.desktop.applyExportPresetImport(presets, 'replace'), [preset('Late', 'explicit overwrite')])
    expect(replacement.ok && replacement.data.preferences.export.savedPresets).toEqual([preset('Late', 'explicit overwrite'), preset('New', 'new entry')])
    expect(session.errors).toEqual([])
  } finally { await stopDesktop(session) }
})
