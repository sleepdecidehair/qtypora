import { test, expect } from '@playwright/test'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { launchDesktop, stopDesktop, openFixture, setSaveDialog, clickNativeMenu, type DesktopSession } from './desktop-helpers'

let session: DesktopSession

test.beforeEach(async () => {
  session = await launchDesktop()
  await session.page.evaluate(async () => {
    const result = await window.desktop.bootstrap()
    if (!result.ok) throw new Error(result.error.message)
    const update = await window.desktop.updatePreferences({ ...result.data.preferences, sourceMode: true, markdown: { ...result.data.preferences.markdown, alerts: true, mathNumbering: true } })
    if (!update.ok) throw new Error(update.error.message)
  })
  await session.page.reload()
  await expect(session.page.locator('.cm-content')).toHaveAttribute('data-mode', 'source')
})

test.afterEach(async () => { if (session) await stopDesktop(session) })

test('YAML、目录和 Alerts 使用统一标题索引，重复标题点击定位且保存不改原文', async () => {
  const prefix = '---\ntitle: 示例标题\nauthor: 测试作者\nnotes: |\n  # 不是标题\n---\n\n[toc]\n\n# 重复标题\n\n> [!WARNING]\n> **注意保存**\n\n'
  const content = prefix + Array.from({ length: 40 }, (_, index) => `段落 ${index}\n`).join('\n') + '\n# 重复标题\n\n最终正文\n'
  const filePath = await openFixture(session, 'features.md', content)
  await session.page.keyboard.press('ControlOrMeta+/')
  await expect(session.page.locator('.md-front-matter')).toContainText('示例标题')
  await expect(session.page.locator('.md-toc a')).toHaveCount(2)
  await expect(session.page.locator('.md-alert-warning')).toContainText('注意保存')
  await session.page.locator('.md-toc a[href="#重复标题-1"]').click()
  const line = content.split('\n').findLastIndex(value => value === '# 重复标题') + 1
  const target = session.page.locator(`.cm-line[data-source-line="${line}"]`)
  await expect(target).toBeVisible()
  await expect.poll(async () => {
    const box = await target.boundingBox()
    const viewport = await session.page.locator('.cm-scroller').boundingBox()
    return Boolean(box && viewport && box.y >= viewport.y - 2 && box.y + box.height <= viewport.y + viewport.height + 2)
  }).toBe(true)
  await session.page.keyboard.press('ControlOrMeta+s')
  await expect.poll(() => readFile(filePath, 'utf8')).toBe(content)
  expect(session.errors).toEqual([])
})

test('YAML 局部编辑可撤销，HTML 导出保留目录锚点并使用元数据', async () => {
  const content = '---\ntitle: Export Title\nauthor: Alice\n---\n\n[toc]\n\n# 标题\n\n正文 <u>下划线</u>\n'
  const filePath = await openFixture(session, 'metadata.md', content)
  await session.page.keyboard.press('ControlOrMeta+/')
  await session.page.locator('.cm-live-block').filter({ has: session.page.locator('.md-front-matter') }).getByRole('button', { name: '编辑此块' }).click()
  await session.page.keyboard.press('ArrowDown')
  await session.page.keyboard.press('End')
  await session.page.keyboard.insertText(' Updated')
  await session.page.keyboard.press('Escape')
  await expect(session.page.locator('.md-front-matter')).toContainText('Export Title Updated')
  await session.page.keyboard.press('ControlOrMeta+s')
  await expect.poll(() => readFile(filePath, 'utf8')).toBe(content.replace('Export Title', 'Export Title Updated'))
  await session.page.keyboard.press('ControlOrMeta+z')
  await session.page.keyboard.press('ControlOrMeta+s')
  await expect.poll(() => readFile(filePath, 'utf8')).toBe(content)
  const output = path.join(session.root, 'metadata.html')
  await setSaveDialog(session, output)
  await clickNativeMenu(session, 'HTML…')
  await expect.poll(async () => { try { return await readFile(output, 'utf8') } catch { return '' } }).toContain('<title>Export Title</title>')
  const html = await readFile(output, 'utf8')
  expect(html).toContain('name="author" content="Alice"')
  expect(html).toContain('href="#标题"')
  expect(html).toContain('id="标题"')
  expect(html).toContain('<u>下划线</u>')
  expect(html).not.toContain('class="md-front-matter"')
})

