test('严格 CommonMark 在预览和导出中保留扩展原文，关闭后恢复扩展设置', async () => {
  const content = '# Strict\n\n==mark== :smile: ~~strike~~\n\n- [x] literal\n\n| A | B |\n|---|---|\n| 1 | 2 |\n'
  const filePath = await openFixture(session, 'strict.md', content)
  await session.page.evaluate(async () => {
    const state = await window.desktop.bootstrap()
    if (!state.ok) throw new Error(state.error.message)
    const result = await window.desktop.patchPreferences({ markdown: { strictMode: true } })
    if (!result.ok) throw new Error(result.error.message)
  })
  await session.page.keyboard.press('ControlOrMeta+/')
  await expect(session.page.locator('.cm-content')).toHaveAttribute('data-mode', 'hybrid')
  await expect(session.page.locator('.cm-content')).toContainText('==mark== :smile: ~~strike~~')
  await expect(session.page.locator('.cm-content table,.cm-content input[type=checkbox],.cm-live-strike')).toHaveCount(0)
  const output = path.join(session.root, 'strict.html')
  await setSaveDialog(session, output)
  await clickNativeMenu(session, 'HTML…')
  await expect.poll(async () => { try { return await readFile(output, 'utf8') } catch { return '' } }).toContain('==mark== :smile: ~~strike~~')
  const html = await readFile(output, 'utf8')
  expect(html).not.toMatch(/<table|<mark>|<s>|type="checkbox"/)
  await session.page.keyboard.press('ControlOrMeta+s')
  await expect.poll(() => readFile(filePath, 'utf8')).toBe(content)
  const settings = await session.page.evaluate(async () => {
    const result = await window.desktop.bootstrap()
    if (!result.ok) throw new Error(result.error.message)
    return result.data.preferences.markdown
  })
  expect(settings.emoji).toBe(true)
  expect(settings.highlight).toBe(true)
  await session.page.evaluate(async options => {
    const state = await window.desktop.bootstrap()
    if (!state.ok) throw new Error(state.error.message)
    const result = await window.desktop.patchPreferences({ markdown: { ...options, strictMode: false } })
    if (!result.ok) throw new Error(result.error.message)
  }, settings)
  await expect(session.page.locator('.cm-live-highlight')).toContainText('mark')
  await expect(session.page.locator('.cm-content table')).toHaveCount(1)
})

