test('媒体沿用文档授权，嵌入内容仅在点击后加载且拒绝任意网页', async () => {
  const wav = Buffer.alloc(44 + 1600)
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8)
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22)
  wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34)
  wav.write('data', 36); wav.writeUInt32LE(1600, 40)
  await writeFile(path.join(session.root, 'tone.wav'), wav)
  let embeddedRequests = 0
  await session.page.route('https://www.youtube-nocookie.com/**', route => { embeddedRequests++; return route.fulfill({ contentType: 'text/html', body: '<p>测试播放器</p>' }) })
  const content = '<audio src="tone.wav" autoplay onplay="alert(1)"></audio>\n\n<iframe src="https://www.youtube-nocookie.com/embed/example?autoplay=1" srcdoc="bad" title="示例视频"></iframe>\n\n<iframe src="https://evil.example/page"></iframe>\n'
  const filePath = await openFixture(session, 'media.md', content)
  await session.page.keyboard.press('ControlOrMeta+/')
  const audio = session.page.locator('.cm-live-block audio')
  await expect.poll(() => audio.evaluate(node => (node as HTMLAudioElement).readyState)).toBeGreaterThanOrEqual(1)
  expect(await audio.evaluate(node => ({ controls: (node as HTMLAudioElement).controls, autoplay: (node as HTMLAudioElement).autoplay, onplay: node.getAttribute('onplay'), src: node.getAttribute('src') }))).toMatchObject({ controls: true, autoplay: false, onplay: null, src: expect.stringMatching(/^qtypora-media:/) })
  await expect(session.page.locator('.cm-live-block iframe')).toHaveCount(0)
  expect(embeddedRequests).toBe(0)
  await session.page.getByRole('button', { name: '加载嵌入内容' }).click()
  await expect.poll(() => embeddedRequests).toBe(1)
  const frame = session.page.locator('.cm-live-block iframe')
  await expect(frame).toHaveCount(1)
  await expect(frame).toHaveAttribute('sandbox', 'allow-scripts allow-same-origin')
  await expect(frame).toHaveAttribute('src', 'https://www.youtube-nocookie.com/embed/example')
  await expect(frame).not.toHaveAttribute('srcdoc')
  await session.page.keyboard.press('ControlOrMeta+s')
  expect(await readFile(filePath, 'utf8')).toBe(content)
})

