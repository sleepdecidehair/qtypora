import { test, expect } from '@playwright/test'
import { mkdir, readFile, writeFile, access, realpath } from 'node:fs/promises'
import path from 'node:path'
import { appendText, launchDesktop, openFixture, redoKey, setContextMenuChoice, setOpenDialog, setSaveDialog, stopDesktop, type DesktopSession } from './desktop-helpers'

let session: DesktopSession
test.beforeEach(async () => { session = await launchDesktop() })
test.afterEach(async () => {
  const errors = [...session.errors]
  await stopDesktop(session)
  expect(errors).toEqual([])
})

async function openFolder(directory: string) {
  await setOpenDialog(session, [directory])
  await session.page.getByTestId('export-menu').click()
  await session.page.getByTestId('open-folder').click()
  await session.page.getByTestId('files-tab').click()
  await expect(session.page.getByTestId('workspace-folder')).toContainText(path.basename(directory))
}

const editorSource = () => session.page.locator('.cm-content').evaluate(element => Reflect.get(element, 'cmTile').root.view.state.doc.toString())

test('新建、副本和普通文件重命名可撤销，删除新建文件仍保留脏稿并可另存', async () => {
  const folder = path.join(session.root, 'file-undo')
  await mkdir(folder)
  const original = '# Original\n', source = path.join(folder, 'original.md')
  await writeFile(source, original)
  await openFolder(folder)
  await session.page.getByRole('button', { name: '在文件夹中新建文件', exact: true }).click()
  await session.page.getByLabel('文件或文件夹名称').fill('created.md')
  await session.page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(session.page.getByRole('dialog')).toHaveCount(0)
  await session.page.getByRole('treeitem', { name: 'created.md', exact: true }).click()
  await expect(session.page.getByTestId('document-name')).toHaveText('created.md')
  await appendText(session, 'Keep this unsaved draft')
  await session.page.getByRole('button', { name: '撤销文件操作', exact: true }).click()
  await expect(session.page.locator('.external-change')).toContainText('已被移动或删除')
  expect(await editorSource()).toBe('Keep this unsaved draft')
  await expect(access(path.join(folder, 'created.md'))).rejects.toMatchObject({ code: 'ENOENT' })
  const recovered = path.join(folder, 'recovered.md')
  await setSaveDialog(session, recovered)
  await session.page.locator('.external-change').getByRole('button', { name: '另存为', exact: true }).click()
  await expect.poll(async () => readFile(recovered, 'utf8').catch(() => '')).toBe('Keep this unsaved draft')
  await session.page.getByRole('treeitem', { name: 'original.md', exact: true }).click()
  await expect(session.page.getByTestId('document-name')).toHaveText('original.md')
  await session.page.getByRole('button', { name: '重命名所选项', exact: true }).click()
  await session.page.getByLabel('文件或文件夹名称').fill('renamed.md')
  await session.page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(session.page.getByTestId('document-name')).toHaveText('renamed.md')
  await session.page.getByRole('button', { name: '撤销文件操作', exact: true }).click()
  await expect(session.page.getByTestId('document-name')).toHaveText('original.md')
  await setContextMenuChoice(session, 'file-duplicate')
  await session.page.getByRole('treeitem', { name: 'original.md', exact: true }).click({ button: 'right' })
  const duplicate = path.join(folder, 'original - 副本.md')
  await expect.poll(async () => readFile(duplicate, 'utf8').catch(() => '')).toBe(original)
  await session.page.getByRole('button', { name: '撤销文件操作', exact: true }).click()
  await expect.poll(async () => access(duplicate).then(() => true, () => false)).toBe(false)
  expect(await readFile(source, 'utf8')).toBe(original)
  expect(await readFile(recovered, 'utf8')).toBe('Keep this unsaved draft')
})

test('目录全词和正则搜索能定位且错误表达式保留原文', async () => {
  const folder = path.join(session.root, 'search-options')
  await mkdir(folder)
  const original = '# Search\n\ncat scatter CAT\n\nTASK-12\n\nTASK-7\n'
  const file = path.join(folder, 'notes.md')
  await writeFile(file, original)
  await openFolder(folder)
  await session.page.getByTestId('search-tab').click()
  const query = session.page.getByTestId('folder-search-input')
  await query.fill('cat')
  await session.page.getByLabel('全词匹配', { exact: true }).check()
  await expect(session.page.locator('.search-result mark')).toHaveText(['cat', 'CAT'])
  await session.page.getByLabel('全词匹配', { exact: true }).uncheck()
  await session.page.getByLabel('正则表达式', { exact: true }).check()
  await query.fill('TASK-\\d+')
  await expect(session.page.locator('.search-result')).toHaveCount(2)
  await session.page.locator('.search-result').last().click()
  await expect(session.page.getByTestId('document-name')).toHaveText('notes.md')
  await expect.poll(editorSource).toBe(original)
  const location = await session.page.locator('.cm-content').evaluate(element => {
    const view = Reflect.get(element, 'cmTile').root.view
    return { line: view.state.doc.lineAt(view.state.selection.main.head).number, point: view.coordsAtPos(view.state.selection.main.head), viewport: view.scrollDOM.getBoundingClientRect().toJSON() }
  })
  expect(location.line).toBe(7)
  expect(location.point.top).toBeGreaterThanOrEqual(location.viewport.top)
  expect(location.point.bottom).toBeLessThanOrEqual(location.viewport.bottom)
  await query.fill('(')
  await expect(session.page.locator('.search-error')).toContainText('正则表达式无效')
  await expect(session.page.locator('.search-result')).toHaveCount(0)
  expect(await editorSource()).toBe(original)
  expect(await readFile(file, 'utf8')).toBe(original)
})

test('文件列表显示策略、排序和固定目录持久保存', async () => {
  const folder = path.join(session.root, 'browse-options')
  await mkdir(folder)
  await mkdir(path.join(folder, 'nested'))
  await Promise.all(['10.md', '2.md', '.hidden.md', 'image.png'].map(name => writeFile(path.join(folder, name), name)))
  await writeFile(path.join(folder, 'nested', 'child.md'), '# nested')
  await openFolder(folder)
  await expect(session.page.locator('.file-tree-row').filter({ hasText: '.hidden.md' })).toHaveCount(0)
  await session.page.getByLabel('隐藏文件', { exact: true }).check()
  await expect(session.page.locator('.file-tree-row').filter({ hasText: '.hidden.md' })).toHaveCount(1)
  await session.page.getByLabel('所有文件', { exact: true }).check()
  await expect(session.page.locator('.file-tree-row').filter({ hasText: 'image.png' })).toHaveCount(1)
  await session.page.getByRole('button', { name: '固定目录', exact: true }).click()
  await expect(session.page.getByRole('button', { name: '取消固定', exact: true })).toBeVisible()
  await session.page.getByLabel('文件视图', { exact: true }).selectOption('list')
  await expect(session.page.locator('.article-list-entry')).toHaveCount(5)
  await session.page.getByLabel('筛选文件名', { exact: true }).fill('*.md,!.hidden*')
  await expect(session.page.locator('.article-list-entry')).toHaveCount(3)
  await session.page.getByLabel('文件夹分组', { exact: true }).uncheck()
  await session.page.getByLabel('倒序', { exact: true }).check()
  await expect(session.page.locator('.article-list-entry strong')).toHaveText(['child.md', '10.md', '2.md'])
  await session.page.locator('.article-list-entry').filter({ hasText: 'child.md' }).click()
  await expect(session.page.getByTestId('document-name')).toHaveText('child.md')
  await expect.poll(editorSource).toBe('# nested')
  await expect.poll(async () => {
    const settings = JSON.parse(await readFile(path.join(session.userData, 'settings.json'), 'utf8'))
    return settings.preferences.workspace
  }).toMatchObject({ view: 'list', showHidden: true, showAllFiles: true, filter: '*.md,!.hidden*', pinnedFolders: [await realpath(folder)] })
})

