test('移动与撤销保持未保存编辑、光标撤销历史及磁盘原字节', async () => {
  const folder = path.join(session.root, 'move-files'), target = path.join(folder, 'target')
  await mkdir(target, { recursive: true })
  const original = '\ufeff# Moving\r\nunchanged\r\n', source = path.join(folder, 'draft.md'), destination = path.join(target, 'draft.md')
  await writeFile(source, original)
  await openFolder(folder)
  await session.page.getByRole('treeitem', { name: 'draft.md', exact: true }).click()
  await expect(session.page.getByTestId('document-name')).toHaveText('draft.md')
  await appendText(session, 'pending')
  const edited = await editorSource()
  expect(edited).toContain('pending')
  await session.page.getByRole('button', { name: '移动所选文件', exact: true }).click()
  await session.page.getByLabel('移动目标文件夹').fill(target)
  await session.page.getByRole('button', { name: '移动', exact: true }).click()
  await expect(session.page.getByRole('dialog', { name: '移动文件' })).toHaveCount(0)
  await expect.poll(async () => readFile(destination, 'utf8').catch(() => '')).toBe(original)
  await expect(access(source)).rejects.toMatchObject({ code: 'ENOENT' })
  expect(await editorSource()).toBe(edited)
  await expect(session.page.locator('.open-document-row').filter({ hasText: 'draft.md' })).toHaveAttribute('title', await realpath(destination))
  await session.page.getByRole('button', { name: '撤销文件操作', exact: true }).click()
  await expect.poll(async () => realpath(source).catch(() => '')).not.toBe('')
  await expect(session.page.locator('.open-document-row').filter({ hasText: 'draft.md' })).toHaveAttribute('title', await realpath(source))
  expect(await readFile(source, 'utf8')).toBe(original)
  expect(await editorSource()).toBe(edited)
  await session.page.locator('.cm-content').click()
  await session.page.keyboard.press('ControlOrMeta+z')
  await expect.poll(editorSource).not.toContain('pending')
  await session.page.keyboard.press(redoKey)
  await expect.poll(editorSource).toBe(edited)
  await session.page.keyboard.press('ControlOrMeta+s')
  await expect.poll(async () => readFile(source, 'utf8')).toContain('pending')
  await expect(access(destination)).rejects.toMatchObject({ code: 'ENOENT' })
})

test('浮动工具栏跟随可见选区，格式操作保留撤销并在切换文档后清理', async () => {
  const original = '# Floating\n\nSelect this phrase.\n\nTail stays intact.\n'
  const file = await openFixture(session, 'floating-toolbar.md', original)
  const from = original.indexOf('Select'), to = from + 'Select this phrase'.length
  const points = await session.page.locator('.cm-content').evaluate((element, range) => {
    const view = Reflect.get(element, 'cmTile').root.view
    return { start: view.coordsAtPos(range.from), end: view.coordsAtPos(range.to), viewport: view.scrollDOM.getBoundingClientRect().toJSON() }
  }, { from, to })
  await session.page.mouse.move(points.start.left, (points.start.top + points.start.bottom) / 2)
  await session.page.mouse.down()
  await session.page.mouse.move(points.end.left, (points.end.top + points.end.bottom) / 2, { steps: 8 })
  await session.page.mouse.up()
  const toolbar = session.page.getByRole('toolbar', { name: '选区格式工具栏' })
  await expect(toolbar).toBeVisible()
  const box = await toolbar.boundingBox()
  expect(box).not.toBeNull()
  expect(box!.x).toBeGreaterThanOrEqual(points.viewport.left)
  expect(box!.y).toBeGreaterThanOrEqual(points.viewport.top)
  expect(box!.x + box!.width).toBeLessThanOrEqual(points.viewport.right)
  expect(box!.y + box!.height).toBeLessThanOrEqual(points.viewport.bottom)
  await toolbar.getByRole('button', { name: '加粗', exact: true }).click()
  const formatted = original.replace('Select this phrase', '**Select this phrase**')
  await expect.poll(editorSource).toBe(formatted)
  await session.page.keyboard.press('ControlOrMeta+z')
  await expect.poll(editorSource).toBe(original)
  await session.page.keyboard.press(redoKey)
  await expect.poll(editorSource).toBe(formatted)
  await session.page.keyboard.press('ControlOrMeta+s')
  await expect.poll(async () => readFile(file, 'utf8')).toBe(formatted)
  await session.page.keyboard.press('ControlOrMeta+n')
  await expect.poll(editorSource).toBe('')
  await expect(toolbar).toHaveCount(0)
})
